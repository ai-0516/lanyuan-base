const fs = require('fs');
const path = require('path');

const repoRoot = path.resolve(__dirname, '..');
const sourcePath = path.join(repoRoot, 'docs/parking/parking_spots_buildings_gates_roads.json');
const outputPath = path.join(repoRoot, 'miniprogram/data/parking.js');
const backendSpotsPath = path.join(repoRoot, 'backend/app/data/parking_spots.py');
const source = JSON.parse(fs.readFileSync(sourcePath, 'utf8'));

const round = value => Number(value.toFixed(6));
const point = (x, y) => ({
  x: round(x / 3370),
  y: round(y / 4299),
});

const targets = [
  ...source.spots.map(spot => {
    const width = spot.landscape ? spot.rect_h : spot.rect_w;
    const height = spot.landscape ? spot.rect_w : spot.rect_h;
    return {
      type: 'spot',
      id: spot.id,
      title: spot.id,
      subtitle: `${spot.area} · ${spot.num}号车位`,
      searchText: `${spot.id} ${spot.area} ${spot.num}号车位`.toLowerCase(),
      ...point(spot.stitched_x + width / 2, spot.stitched_y + height / 2),
      left: round(spot.stitched_x / 3370),
      top: round(spot.stitched_y / 4299),
      width: round(width / 3370),
      height: round(height / 4299),
      landscape: spot.landscape,
    };
  }),
  ...source.buildings.map(building => ({
    type: 'building',
    id: building.id,
    title: `${building.id}楼`,
    subtitle: '楼栋',
    searchText: `${building.id} ${building.id.replace('#', '')}号楼 ${building.id}楼`.toLowerCase(),
    ...point(building.x + building.w / 2, building.y + building.h / 2),
  })),
  ...source.gates.map(gate => ({
    type: 'gate',
    id: gate.id,
    title: gate.id,
    subtitle: '停车场出入口',
    searchText: `${gate.id} 出入口 门`.toLowerCase(),
    ...point(gate.x + gate.w / 2, gate.y + gate.h / 2),
  })),
];

const roadGraph = {
  nodes: source.road_graph.nodes.map(node => ({
    id: node.id,
    x: node.x,
    y: node.y,
  })),
  edges: source.road_graph.edges.map(edge => ({
    from: edge.from,
    to: edge.to,
    roadIndex: edge.roadIdx,
    length: edge.length,
  })),
  directions: source.roads.map(road => road.direction),
};

const output = `// Generated by scripts/generate-parking-data.js. Do not edit manually.\nmodule.exports = ${JSON.stringify({
  imageWidth: 3370,
  imageHeight: 4299,
  targets,
  roadGraph,
}, null, 2)};\n`;

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, output);
const backendOutput = `# Generated by scripts/generate-parking-data.js. Do not edit manually.\nPARKING_SPOT_IDS = frozenset(${JSON.stringify(source.spots.map(spot => spot.id), null, 2)})\n`;
fs.mkdirSync(path.dirname(backendSpotsPath), { recursive: true });
fs.writeFileSync(backendSpotsPath, backendOutput);
console.log(`Generated ${targets.length} parking targets at ${outputPath}`);
